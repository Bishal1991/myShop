class Product {
  final String id;
  final String name;
  final String category;
  final double price;
  final double rating;
  final String iconName;
  final String description;
  final String imageUrl;

  const Product({
    required this.id,
    required this.name,
    required this.category,
    required this.price,
    required this.rating,
    required this.iconName,
    required this.description,
    required this.imageUrl,
  });
}